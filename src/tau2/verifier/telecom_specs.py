"""
Auto-generated specs for telecom domain tasks.

Telecom tasks are combinatorial: each task ID encodes a category and a set of
"fault injections" (e.g., airplane_mode_on, data_usage_exceeded). The fix for
each fault is deterministic, so the spec is generated by parsing the task ID
and computing the expected agent WRITE actions.

Telecom agent WRITE tools:
- send_payment_request (for overdue_bill_suspension)
- resume_line (for overdue_bill_suspension, after payment)
- enable_roaming (for user_abroad_roaming_disabled_*)
- refuel_data (for data_usage_exceeded)
- suspend_line (not expected in any standard fault fix)
- disable_roaming (not expected in any standard fault fix)
- transfer_to_human_agents (for lock_sim_card_pin, contract_end_suspension)

All other fault fixes are user-side actions (toggle_airplane_mode, etc.)
and don't involve agent WRITE tools.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

from tau2.verifier.spec import ActionConstraint, TaskSpec

logger = logging.getLogger(__name__)

# All agent WRITE tools in telecom
TELECOM_WRITE_TOOLS = {
    "send_payment_request",
    "resume_line",
    "enable_roaming",
    "disable_roaming",
    "refuel_data",
    "suspend_line",
}

# Fixed customer/line IDs for all telecom tasks
CUSTOMER_ID = "C1001"
LINE_ID = "L1002"
BILL_ID = "B1234321"

# Mapping: fault name → list of (agent_tool_name, args) that the agent must call
# Only includes agent-side WRITE actions (user-side self-fixes are not tracked)
FAULT_TO_AGENT_WRITES: dict[str, list[tuple[str, dict]]] = {
    # Faults requiring agent WRITE actions
    "overdue_bill_suspension": [
        ("send_payment_request", {"customer_id": CUSTOMER_ID, "bill_id": BILL_ID}),
        ("resume_line", {"customer_id": CUSTOMER_ID, "line_id": LINE_ID}),
    ],
    "data_usage_exceeded": [
        ("refuel_data", {"customer_id": CUSTOMER_ID, "line_id": LINE_ID, "gb_amount": 2.0}),
    ],
    "user_abroad_roaming_disabled_on": [
        ("enable_roaming", {"customer_id": CUSTOMER_ID, "line_id": LINE_ID}),
    ],
    "user_abroad_roaming_disabled_off": [
        ("enable_roaming", {"customer_id": CUSTOMER_ID, "line_id": LINE_ID}),
    ],
    # Faults requiring escalation
    "lock_sim_card_pin": [
        ("transfer_to_human_agents", {}),
    ],
    "contract_end_suspension": [
        ("transfer_to_human_agents", {}),
    ],
    # Faults that are user-side only (no agent writes)
    "airplane_mode_on": [],
    "unseat_sim_card": [],
    "break_apn_settings": [],
    "data_mode_off": [],
    "data_saver_mode_on": [],
    "bad_network_preference": [],
    "bad_vpn": [],
    "bad_wifi_calling": [],
    "break_apn_mms_setting": [],
    "break_app_sms_permission": [],
    "break_app_storage_permission": [],
    "break_app_both_permissions": [],
    "user_abroad_roaming_enabled_off": [],
}

# Faults that always require transfer (unsolvable by agent alone)
ESCALATION_FAULTS = {"lock_sim_card_pin", "contract_end_suspension"}


def _parse_task_id(task_id: str) -> tuple[str, list[str], str]:
    """Parse a telecom task ID into (category, faults, persona).

    Format: [category]fault1|fault2|...[PERSONA:X]
    """
    # Extract category
    cat_end = task_id.index("]")
    category = task_id[1:cat_end]

    rest = task_id[cat_end + 1:]

    # Extract persona
    persona_start = rest.index("[PERSONA:")
    faults_str = rest[:persona_start]
    persona = rest[persona_start + 9:-1]  # strip [PERSONA: and ]

    faults = faults_str.split("|") if faults_str else []
    return category, faults, persona


def _build_spec_from_faults(task_id: str, category: str, faults: list[str]) -> TaskSpec:
    """Build a TaskSpec from the parsed fault list."""
    needs_escalation = bool(set(faults) & ESCALATION_FAULTS)

    # Collect expected agent WRITE actions
    expected_writes: list[ActionConstraint] = []
    expected_write_names: set[str] = set()
    seen: set[str] = set()

    for fault in faults:
        agent_writes = FAULT_TO_AGENT_WRITES.get(fault, [])
        for tool_name, args in agent_writes:
            # Dedup
            dedup_key = f"{tool_name}:{sorted(args.items())}"
            if dedup_key in seen:
                continue
            seen.add(dedup_key)

            expected_write_names.add(tool_name)

            if tool_name == "transfer_to_human_agents":
                expected_writes.append(
                    ActionConstraint(
                        tool_name=tool_name,
                        required_args={},
                        compare_args=[],
                        description=f"Escalate due to {fault}",
                    )
                )
            else:
                compare_keys = list(args.keys())
                expected_writes.append(
                    ActionConstraint(
                        tool_name=tool_name,
                        required_args=args,
                        compare_args=compare_keys,
                        description=f"Fix {fault}",
                    )
                )

    # Calculate forbidden writes
    forbidden = TELECOM_WRITE_TOOLS - expected_write_names
    max_writes = None if expected_writes else 0

    fault_str = ", ".join(faults)
    description = f"[{category}] Fix faults: {fault_str}"
    if needs_escalation:
        description += " (requires escalation to human)"

    return TaskSpec(
        task_id=task_id,
        description=description,
        forbidden_write_tools=forbidden,
        allowed_write_actions=expected_writes,
        max_write_calls=max_writes,
        notes=f"Category: {category}. Faults: {fault_str}. Escalation: {needs_escalation}",
    )


def build_telecom_specs(task_ids: list[str] | None = None) -> dict[str, TaskSpec]:
    """Build specs for telecom tasks.

    If task_ids is None, builds specs for all tasks in tasks.json.
    Otherwise, builds specs only for the specified task IDs.

    Since telecom tasks are combinatorial (fault-based), specs are generated
    by parsing the task ID rather than being manually defined.
    """
    if task_ids is None:
        # Load all tasks
        from tau2.utils.utils import DATA_DIR
        tasks_path = DATA_DIR / "tau2" / "domains" / "telecom" / "tasks.json"
        with open(tasks_path) as f:
            all_tasks = json.load(f)
        task_ids = [t["id"] for t in all_tasks]

    specs: dict[str, TaskSpec] = {}
    for task_id in task_ids:
        try:
            category, faults, persona = _parse_task_id(task_id)
            specs[task_id] = _build_spec_from_faults(task_id, category, faults)
        except (ValueError, IndexError) as e:
            logger.warning(f"Could not parse telecom task ID '{task_id}': {e}")
            continue

    return specs


def get_spec(task_id: str) -> TaskSpec:
    """Get the spec for a specific telecom task."""
    try:
        category, faults, persona = _parse_task_id(task_id)
    except (ValueError, IndexError) as e:
        raise ValueError(f"Cannot parse telecom task_id='{task_id}': {e}")
    return _build_spec_from_faults(task_id, category, faults)
